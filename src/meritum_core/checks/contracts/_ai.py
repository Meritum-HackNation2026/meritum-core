"""The machine-readable marker that an AI system wrote the answer (AI Act art. 50(2)).

Features:
    US-BEZ-07
"""

from __future__ import annotations

from datetime import datetime
from typing import TYPE_CHECKING, Annotated, Literal

from pydantic import Field

from ._base import _Model

if TYPE_CHECKING:
    from ._records import ModelUsage


class AiMarker(_Model):
    """Machine-readable marker that an AI system wrote the verdicts and justifications.

    Every channel gets the same marker from the result; how a channel shows it is up to
    the channel.

    Attributes:
        ai_generated: always true; the content was generated by an AI system. Unlike
            CheckResult.ai_disclosure, which every result has, the marker names
            the model, so it exists only where a model wrote the answer.
        provider: the provider of the model that wrote the justification.
        model: the pinned model version that wrote the justification.
        generated_at: when the model wrote it.

    Features:
        US-BEZ-07
    """

    ai_generated: Literal[True] = True
    # Own titles keep the generated TS names of ModelUsage.provider/model unchanged.
    # Same limits as ModelUsage, so ai_marker_for accepts every recorded call.
    provider: Annotated[str, Field(max_length=60, title="Marker Provider")]
    model: Annotated[str, Field(max_length=80, title="Marker Model")]
    generated_at: datetime


def ai_marker_for(usage: ModelUsage, generated_at: datetime) -> AiMarker:
    """Build the AI marker from the model call that wrote the justification.

    Args:
        usage: the recorded model call; its provider and model go into the marker.
        generated_at: when the model wrote the justification.

    Returns:
        The marker for CheckResult.ai_marker and CachedResult.ai_marker.

    Features:
        US-BEZ-07
    """
    return AiMarker(
        provider=usage.provider, model=usage.model, generated_at=generated_at
    )
